/* Bellezza & Co. — site behavior. All content (nav, hours, prices) is in the
   HTML already; this file only adds behavior. The CONFIG block is generated by
   tools/build-partials.py from tools/site.json — do not edit it by hand. */
(function () {
  'use strict';

  /* config:start */
  var CONFIG = {"tz": "America/New_York", "hours": {"Mon": ["09:00", "20:00"], "Tue": ["09:00", "20:00"], "Wed": ["12:00", "20:00"], "Thu": ["09:00", "20:00"], "Fri": ["09:00", "19:00"], "Sat": ["08:00", "15:00"], "Sun": null}, "holidays": [{"date": "2026-12-24", "name": "Christmas Eve", "closed": false, "closes": "12:00"}, {"date": "2026-12-25", "name": "Christmas", "closed": true, "closes": null}, {"date": "2026-12-26", "name": "December 26", "closed": true, "closes": null}, {"date": "2026-12-31", "name": "New Year's Eve", "closed": false, "closes": "12:00"}, {"date": "2027-01-01", "name": "New Year's Day", "closed": true, "closes": null}, {"date": "2027-05-31", "name": "Memorial Day", "closed": true, "closes": null}, {"date": "2027-07-03", "name": "July 3rd", "closed": false, "closes": "17:00"}, {"date": "2027-07-04", "name": "Independence Day", "closed": true, "closes": null}, {"date": "2027-09-06", "name": "Labor Day", "closed": true, "closes": null}], "giftSeasons": [["2026-11-01", "2026-12-24"], ["2026-02-01", "2026-02-14"], ["2026-04-26", "2026-05-10"], ["2027-11-01", "2027-12-24"], ["2027-02-01", "2027-02-14"], ["2027-04-25", "2027-05-09"]], "phone": "740-366-1604"};
  /* config:end */

  var doc = document;
  var root = doc.documentElement;
  var $ = function (sel, ctx) { return (ctx || doc).querySelector(sel); };
  var $$ = function (sel, ctx) { return Array.prototype.slice.call((ctx || doc).querySelectorAll(sel)); };
  var mqDesktop = window.matchMedia('(min-width: 1024px)');

  /* ---------- owner photo-slot view: add ?photos=1 to any URL ---------- */
  if (/[?&]photos=1\b/.test(location.search)) {
    root.classList.add('show-ph');
  }

  /* ---------- time in Newark (never the device clock's zone) ---------- */
  var DAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  var DAY_NAMES = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

  function nowInNewark() {
    var parts = {};
    new Intl.DateTimeFormat('en-US', {
      timeZone: CONFIG.tz || 'America/New_York', hour12: false,
      year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', weekday: 'short'
    }).formatToParts(new Date()).forEach(function (p) { parts[p.type] = p.value; });
    var hour = parseInt(parts.hour, 10) % 24;
    return {
      iso: parts.year + '-' + parts.month + '-' + parts.day,
      month: parts.month + '-' + parts.day,
      dow: DAYS.indexOf(parts.weekday),
      minutes: hour * 60 + parseInt(parts.minute, 10)
    };
  }
  function toMin(hhmm) { var p = hhmm.split(':'); return +p[0] * 60 + +p[1]; }
  function fmt(hhmm) {
    var p = hhmm.split(':'), h = +p[0], m = +p[1];
    var s = (h % 12 || 12) + (m ? ':' + (m < 10 ? '0' : '') + m : '');
    return s + (h < 12 ? 'am' : 'pm');
  }
  function addDays(iso, n) {
    var d = new Date(iso + 'T12:00:00Z'); d.setUTCDate(d.getUTCDate() + n);
    return d.toISOString().slice(0, 10);
  }
  function holidayOn(iso) {
    return (CONFIG.holidays || []).filter(function (h) { return h.date === iso; })[0] || null;
  }
  /* opening window for a given date: [opens, closes] or null */
  function windowFor(iso, dow) {
    var base = (CONFIG.hours || {})[DAYS[dow]];
    var hol = holidayOn(iso);
    if (hol && hol.closed) return { closed: true, holiday: hol };
    if (!base) return { closed: true };
    var closes = hol && hol.closes ? hol.closes : base[1];
    return { opens: base[0], closes: closes, early: !!(hol && hol.closes), holiday: hol };
  }

  function computeStatus() {
    if (!CONFIG.hours) return null;
    var n = nowInNewark();
    var today = windowFor(n.iso, n.dow);
    if (!today.closed) {
      if (n.minutes >= toMin(today.opens) && n.minutes < toMin(today.closes)) {
        return { state: 'open', text: (today.early ? 'Closing early today at ' : 'Open now · until ') + fmt(today.closes), today: today };
      }
      if (n.minutes < toMin(today.opens)) {
        return { state: 'later', text: 'Opens today at ' + fmt(today.opens), today: today, next: 'today at ' + fmt(today.opens) };
      }
    }
    for (var i = 1; i <= 8; i++) {
      var iso = addDays(n.iso, i), dow = (n.dow + i) % 7, w = windowFor(iso, dow);
      if (!w.closed) {
        var when = (i === 1 ? 'tomorrow' : DAYS[dow]) + ' at ' + fmt(w.opens);
        var pre = today.holiday && today.closed ? 'Closed today for ' + today.holiday.name + ' · ' : '';
        return { state: 'closed', text: pre + 'Book online 24/7 · We open ' + when, today: today, next: when };
      }
    }
    return null;
  }

  function applyStatus() {
    var s = computeStatus();
    if (!s) return;
    $$('[data-status]').forEach(function (el) {
      el.textContent = s.text;
      el.setAttribute('data-state', s.state);
      el.classList.add('status');
      el.hidden = false;
    });
    var n = nowInNewark();
    var name = DAY_NAMES[n.dow];
    $$('table.hours tr[data-day]').forEach(function (tr) {
      if (tr.getAttribute('data-day') !== name) return;
      tr.setAttribute('aria-current', 'date');
      var th = tr.querySelector('th');
      if (th && !th.querySelector('.today-tag')) {
        var tag = doc.createElement('span'); tag.className = 'today-tag'; tag.textContent = 'Today';
        th.appendChild(tag);
      }
    });
    $$('[data-today-hours]').forEach(function (el) {
      var t = s.today;
      el.textContent = t && !t.closed ? fmt(t.opens) + '–' + fmt(t.closes) : 'Closed' + (t && t.holiday ? ' (' + t.holiday.name + ')' : '');
    });
    if (s.state !== 'open' && s.next) {
      $$('[data-call-label]').forEach(function (a) {
        if (!a.querySelector('.call-note')) {
          var sm = doc.createElement('span'); sm.className = 'call-note'; sm.textContent = ' · opens ' + s.next.replace(/^(today|tomorrow|\w{3}) at /, '');
          a.appendChild(sm);
        }
      });
    }
  }

  /* ---------- gift seasons & expiring specials ---------- */
  function applySeasons() {
    var iso = nowInNewark().iso;
    var inSeason = (CONFIG.giftSeasons || []).some(function (w) { return iso >= w[0] && iso <= w[1]; });
    $$('[data-gift-label]').forEach(function (el) {
      el.hidden = (el.getAttribute('data-gift-label') === 'on') !== inSeason;
    });
    $$('[data-gift-season]').forEach(function (el) { el.hidden = !inSeason; });
    $$('[data-ends]').forEach(function (el) {
      var end = el.getAttribute('data-ends');
      if (end && iso > end) el.hidden = true;
    });
  }

  /* ---------- header: scrolled state ---------- */
  function initHeader() {
    var header = $('.site-header');
    if (!header) return;
    var onScroll = function () { header.classList.toggle('is-scrolled', window.scrollY > 80); };
    window.addEventListener('scroll', onScroll, { passive: true });
    onScroll();
  }

  /* ---------- services disclosure (APG pattern, no role=menu) ---------- */
  function initServicesNav() {
    var btn = $('.nav-services .chev');
    var panel = $('#nav-services');
    if (!btn || !panel) return;
    btn.hidden = false;
    var li = btn.parentNode, openTimer, closeTimer, suppressHover = false, byHover = false;
    function set(open) {
      btn.setAttribute('aria-expanded', open ? 'true' : 'false');
      panel.hidden = !open;
      if (!open) byHover = false;
    }
    btn.addEventListener('click', function (e) {
      /* a pointer user who hovered the panel open and then clicks the chevron expects it to stay open */
      if (byHover && e.detail > 0) { byHover = false; return; }
      set(btn.getAttribute('aria-expanded') !== 'true');
    });
    li.addEventListener('mouseenter', function () {
      if (!mqDesktop.matches || suppressHover) return;
      clearTimeout(closeTimer);
      openTimer = setTimeout(function () { if (btn.getAttribute('aria-expanded') !== 'true') { set(true); byHover = true; } }, 150);
    });
    li.addEventListener('mouseleave', function () {
      clearTimeout(openTimer); suppressHover = false;
      closeTimer = setTimeout(function () { set(false); }, 300);
    });
    doc.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && btn.getAttribute('aria-expanded') === 'true') {
        var had = li.contains(doc.activeElement);
        set(false); suppressHover = true; if (had) btn.focus();
      }
    });
    doc.addEventListener('click', function (e) { if (!li.contains(e.target)) set(false); });
    li.addEventListener('focusout', function (e) { if (!li.contains(e.relatedTarget)) set(false); });
  }

  /* ---------- mobile menu drawer ---------- */
  function initDrawer() {
    var link = $('[data-menu-toggle]');
    var drawer = $('#drawer');
    if (!link || !drawer || typeof drawer.showModal !== 'function') return;
    var btn = doc.createElement('button');
    btn.type = 'button';
    btn.className = link.className;
    btn.innerHTML = link.innerHTML;
    btn.setAttribute('aria-expanded', 'false');
    btn.setAttribute('aria-controls', 'drawer');
    link.parentNode.replaceChild(btn, link);
    btn.addEventListener('click', function () {
      drawer.showModal(); btn.setAttribute('aria-expanded', 'true'); syncBookbar();
    });
    drawer.addEventListener('close', function () { btn.setAttribute('aria-expanded', 'false'); syncBookbar(); });
    $$('[data-drawer-close]', drawer).forEach(function (b) { b.addEventListener('click', function () { drawer.close(); }); });
    drawer.addEventListener('click', function (e) { if (e.target === drawer) drawer.close(); });
    $$('a', drawer).forEach(function (a) {
      a.addEventListener('click', function () { if (a.getAttribute('href').charAt(0) === '#') drawer.close(); });
    });
  }

  /* ---------- mobile bottom bar: after hero CTAs, not over band/footer ---------- */
  var bar, heroGone = false, bandVisible = false;
  function syncBookbar() {
    if (!bar) return;
    var dialogOpen = !!$('dialog[open]');
    bar.setAttribute('data-hidden', (!heroGone || bandVisible || dialogOpen) ? 'true' : 'false');
  }
  function initBookbar() {
    bar = $('[data-bookbar]');
    if (!bar || !('IntersectionObserver' in window)) { if (bar) bar.setAttribute('data-hidden', 'false'); return; }
    var main = $('main');
    var hero = $('[data-hero-ctas]') || (main && main.querySelector('.btn--book, .btn--strong'));
    if (hero) {
      new IntersectionObserver(function (es) {
        es.forEach(function (e) { heroGone = !e.isIntersecting && e.boundingClientRect.top < 0; });
        syncBookbar();
      }).observe(hero);
    } else { heroGone = true; }
    var ends = $$('[data-band], .site-footer');
    var visible = new Set();
    var io = new IntersectionObserver(function (es) {
      es.forEach(function (e) { if (e.isIntersecting) visible.add(e.target); else visible.delete(e.target); });
      bandVisible = visible.size > 0; syncBookbar();
    });
    ends.forEach(function (el) { io.observe(el); });
    syncBookbar();
  }

  /* ---------- keep focused elements clear of sticky chrome (WCAG 2.4.11) ---------- */
  function initFocusClearance() {
    doc.addEventListener('focusin', function (e) {
      var el = e.target;
      if (el.closest && el.closest('.chips')) { el.scrollIntoView({ block: 'nearest', inline: 'nearest' }); return; }
      if (!el.getBoundingClientRect || el.closest('.site-header, .bookbar, dialog, .jump-chips, .team-filters')) return;
      var r = el.getBoundingClientRect();
      var header = $('.site-header'), chips = $('.jump-chips') || $('.team-filters');
      var topCover = 0;
      [header, chips].forEach(function (x) {
        if (!x || getComputedStyle(x).position !== 'sticky') return;
        var xr = x.getBoundingClientRect();
        /* count sticky chrome only while it is stuck at its top offset; an unstuck chips row further down covers nothing */
        if (xr.top <= (parseFloat(getComputedStyle(x).top) || 0) + 1) topCover = Math.max(topCover, xr.bottom);
      });
      var bottomCover = bar && bar.getAttribute('data-hidden') === 'false' ? bar.getBoundingClientRect().top : window.innerHeight;
      if (r.top < topCover + 8) window.scrollBy(0, r.top - topCover - 16);
      else if (r.bottom > bottomCover - 8) window.scrollBy(0, r.bottom - bottomCover + 16);
    });
  }

  /* ---------- bio dialogs ---------- */
  function initDialogs() {
    $$('[data-bio]').forEach(function (btn) {
      var dlg = doc.getElementById(btn.getAttribute('data-bio'));
      if (!dlg || typeof dlg.showModal !== 'function') return;
      btn.addEventListener('click', function (e) { e.preventDefault(); dlg.showModal(); syncBookbar(); });
    });
    $$('dialog.bio').forEach(function (dlg) {
      $$('.bio-close', dlg).forEach(function (b) { b.addEventListener('click', function () { dlg.close(); }); });
      dlg.addEventListener('click', function (e) { if (e.target === dlg) dlg.close(); });
      dlg.addEventListener('close', syncBookbar);
    });
  }

  /* ---------- team filters (our-team.html) ---------- */
  function initTeamFilters() {
    var wrap = $('[data-team-filters]');
    if (!wrap) return;
    var chips = $$('button[data-filter]', wrap);
    var items = $$('.team-item');
    var live = $('[data-filter-count]');
    function apply(key, fromHash) {
      var shown = 0;
      chips.forEach(function (c) { c.setAttribute('aria-pressed', c.getAttribute('data-filter') === key ? 'true' : 'false'); });
      items.forEach(function (li) {
        var depts = (li.getAttribute('data-dept') || '').split(' ');
        var on = key === 'all' || depts.indexOf(key) > -1;
        li.hidden = !on; if (on) shown++;
      });
      var chip = chips.filter(function (c) { return c.getAttribute('data-filter') === key; })[0];
      if (live) live.textContent = 'Showing ' + shown + ' ' + (key === 'all' ? 'people' : (chip ? chip.getAttribute('data-noun') || chip.textContent.trim().toLowerCase() : ''));
      if (!fromHash) history.replaceState(null, '', key === 'all' ? location.pathname : '#filter-' + key);
    }
    chips.forEach(function (c) { c.addEventListener('click', function () { apply(c.getAttribute('data-filter')); }); });
    var m = /^#filter-([\w-]+)$/.exec(location.hash);
    if (m && chips.some(function (c) { return c.getAttribute('data-filter') === m[1]; })) apply(m[1], true);
  }

  /* ---------- jump chips scrollspy ---------- */
  function initScrollspy() {
    var nav = $('.jump-chips');
    if (!nav || !('IntersectionObserver' in window)) return;
    var links = $$('a[href^="#"]', nav).filter(function (a) { return a.getAttribute('href').length > 1; });
    var targets = links.map(function (a) { return doc.getElementById(a.getAttribute('href').slice(1)); }).filter(Boolean);
    root.style.setProperty('--chips-h', nav.offsetHeight + 'px');
    var current = null;
    var io = new IntersectionObserver(function () {
      var line = window.innerHeight * 0.35, next = null;
      var best = -Infinity; targets.forEach(function (t) { var top = t.getBoundingClientRect().top; if (top <= line && top > best) { best = top; next = t.id; } });
      if (next === current) return;
      current = next;
      links.forEach(function (a) {
        if (a.getAttribute('href') === '#' + current) {
          a.setAttribute('aria-current', 'true');
          a.scrollIntoView({ block: 'nearest', inline: 'nearest' });
        } else a.removeAttribute('aria-current');
      });
    }, { rootMargin: '-35% 0px -60% 0px' });
    targets.forEach(function (t) { io.observe(t); });
  }

  /* ---------- map facade ---------- */
  function initMaps() {
    $$('[data-map]').forEach(function (btn) {
      btn.addEventListener('click', function () {
        var f = doc.createElement('iframe');
        f.src = btn.getAttribute('data-map');
        f.title = 'Map to Bellezza & Co., 206 Deo Drive, Newark, Ohio';
        f.loading = 'lazy';
        f.referrerPolicy = 'no-referrer-when-downgrade';
        /* replace only the button (keep the address text) and keep focus where the user was (2.4.3) */
        btn.replaceWith(f);
        f.focus();
      });
    });
  }

  /* ---------- analytics hook (cookieless; no-op until a provider is added) ---------- */
  function initAnalytics() {
    doc.addEventListener('click', function (e) {
      var a = e.target.closest('[data-cta]');
      if (!a || typeof window.plausible !== 'function') return;
      window.plausible(a.getAttribute('data-cta'), { props: { placement: a.getAttribute('data-placement') || '', page: location.pathname } });
    });
  }

  function ready(fn) { if (doc.readyState !== 'loading') fn(); else doc.addEventListener('DOMContentLoaded', fn); }
  ready(function () {
    [applyStatus, applySeasons, initHeader, initServicesNav, initDrawer, initBookbar, initFocusClearance,
      initDialogs, initTeamFilters, initScrollspy, initMaps, initAnalytics].forEach(function (fn) {
      try { fn(); } catch (err) { if (window.console) console.error(err); }
    });
  });
})();
